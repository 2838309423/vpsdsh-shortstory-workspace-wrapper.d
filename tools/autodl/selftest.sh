#!/usr/bin/env bash
# selftest.sh -- machine-checkable acceptance test for the AutoDL system-disk image.
# Runs WITHOUT a GPU (safe in 无卡模式 / 0.5-core session).
#
# Usage: bash selftest.sh [--work /root/autodl-tmp/_selftest] [--samples 8] [--res 320x180]
# Output: one line per assertion, then:  __SELFTEST__ <total> <failed>
set -u

WORK=""; [ -d /root/autodl-tmp ] && WORK="/root/autodl-tmp/_selftest" || WORK="/tmp/_selftest"
SAMPLES=8; RES="320x180"
while [ $# -gt 0 ]; do
  case "$1" in
    --work) WORK="${2:-}"; shift ;;
    --samples) SAMPLES="${2:-}"; shift ;;
    --res) RES="${2:-}"; shift ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac; shift
done

HERE="$(cd "$(dirname "$0")" && pwd)"
EXPECT_VER="${BLENDER_VER:-4.5.14}"
TOTAL=0; FAIL=0
ok()   { TOTAL=$((TOTAL+1)); printf '  OK   %s\n' "$1"; }
bad()  { TOTAL=$((TOTAL+1)); FAIL=$((FAIL+1)); printf '  FAIL %s\n' "$1"; }
info() { printf '  ..   %s\n' "$1"; }
check() { if [ "$1" = "1" ]; then ok "$2"; else bad "$2"; fi; }

mkdir -p "$WORK"
echo "=== selftest @ $(hostname) $(uname -r) $(date -u +%Y-%m-%dT%H:%M:%SZ) ==="

# ---- resolve launcher + real binary (launcher is a wrapper script, on purpose) ----
BL="$(command -v blender 2>/dev/null || true)"
REAL=""
if [ -n "$BL" ]; then
  if [ -L "$BL" ]; then REAL="$(readlink -f "$BL")"; fi
  if [ -z "$REAL" ] && head -c 2 "$BL" 2>/dev/null | grep -q '#!'; then
    REAL="$(sed -n 's|^exec "\(.*\)" "\$@"$|\1|p' "$BL" | head -n 1)"
    EXTRA="$(sed -n 's|^BLENDER_LIBDIR="\(.*\)"$|\1|p' "$BL" | head -n 1)"
    [ -n "${EXTRA:-}" ] && export LD_LIBRARY_PATH="$EXTRA${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
  fi
  [ -n "$REAL" ] && [ -x "$REAL" ] || REAL="$BL"
fi

# 1) launcher
[ -n "$BL" ] && check 1 "blender launcher on PATH: $BL" || check 0 "blender launcher on PATH"

# 2) version  (strict: the line must START with "Blender <ver>" -- a path containing
#    "4.5.14" used to make a broken launcher look OK)
VER_LINE=""
[ -n "$BL" ] && VER_LINE="$(blender --version 2>&1 | head -n 1)"
case "$VER_LINE" in
  "Blender $EXPECT_VER"*) check 1 "version matches $EXPECT_VER ($VER_LINE)" ;;
  *) check 0 "version matches $EXPECT_VER (got: ${VER_LINE:-none})" ;;
esac

# 3) launcher sanity: the REAL binary must be Blender's multi-MB ELF, not our wrapper
if [ -n "$REAL" ]; then
  RSZ="$(stat -c%s "$REAL" 2>/dev/null || echo 0)"
  if [ "$RSZ" -gt 1000000 ] && ! grep -q 'generated by bootstrap.sh' "$REAL" 2>/dev/null; then
    check 1 "real launcher sane (${RSZ} B, not the bootstrap wrapper)"
  else
    check 0 "real launcher sane (got ${RSZ} B -- clobbered by wrapper? re-run bootstrap.sh)"
  fi
fi

# 4) no missing shared libraries (checked on the REAL binary, $ORIGIN intact)
if [ -n "$REAL" ]; then
  MISSING="$(ldd "$REAL" 2>/dev/null | grep 'not found' || true)"
  [ -z "$MISSING" ] && check 1 "no missing shared libs" || { check 0 "missing shared libs"; printf '%s\n' "$MISSING" | sed 's/^/       /'; }
fi

# 5) python inside blender
if [ -n "$BL" ]; then
  PYV="$(blender --factory-startup -b --python-expr 'import sys;print("__PY__",sys.version.split()[0])' 2>/dev/null | grep -o '__PY__ .*' | tail -n 1 || true)"
  case "${PYV:-}" in __PY__*) check 1 "blender python ok ($PYV)" ;; *) check 0 "blender python ok" ;; esac
fi

# 5) ffmpeg
FF="$(command -v ffmpeg 2>/dev/null || true)"
[ -n "$FF" ] && check 1 "ffmpeg on PATH ($("$FF" -version 2>/dev/null | head -n 1 | cut -c1-40))" || check 0 "ffmpeg on PATH"

# 6) disk layout
info "system disk: $(df -h / | tail -n 1)"
if [ -d /root/autodl-tmp ]; then
  info "data disk  : $(df -h /root/autodl-tmp | tail -n 1)"
  DM="$(df --output=target /root/autodl-tmp | tail -n 1)"
  [ "$DM" = "/root/autodl-tmp" ] && check 1 "data disk is a separate mount ($DM)" || check 0 "data disk is a separate mount (got ${DM:-none})"
else
  info "no /root/autodl-tmp (not an AutoDL container?)"
fi

# 7) GPU presence -- informational, never a failure in no-GPU mode
if command -v nvidia-smi >/dev/null 2>&1 && nvidia-smi -L >/dev/null 2>&1; then
  info "GPU: $(nvidia-smi --query-gpu=name,driver_version,memory.total --format=csv,noheader | head -n 1)"
else
  info "GPU: not visible (expected in 无卡模式 / CPU-only box)"
fi
if ldconfig -p 2>/dev/null | grep -q 'libcuda.so.1'; then info "libcuda.so.1: present"; else info "libcuda.so.1: absent (must be present for Cycles CUDA)"; fi

# 8) real Cycles CPU render
if [ -n "$BL" ]; then
  OUT="$WORK/smoke_$(date -u +%H%M%S).png"
  LOG="$WORK/smoke.log"
  blender --factory-startup -b --python-exit-code 1 --python "$HERE/smoke_cpu.py" -- \
          --out "$OUT" --res "$RES" --samples "$SAMPLES" >"$LOG" 2>&1
  RC=$?
  LINE="$(grep -o '__SMOKE__ .*' "$LOG" | tail -n 1)"
  if [ "$RC" = "0" ] && [ -n "$LINE" ]; then
    check 1 "Cycles CPU render ($RES/${SAMPLES}spp): $LINE"
    [ -s "$OUT" ] && check 1 "PNG written: $OUT ($(stat -c%s "$OUT") B)" || check 0 "PNG written"
  else
    check 0 "Cycles CPU render (rc=$RC, log: $LOG)"
    tail -n 20 "$LOG" | sed 's/^/       /'
  fi
fi

echo "__SELFTEST__ $TOTAL $FAIL"
[ "$FAIL" = "0" ] || exit 1
exit 0
