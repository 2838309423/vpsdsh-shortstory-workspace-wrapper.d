#!/usr/bin/env bash
# bootstrap.sh -- Blender 4.5.14 LTS runtime bootstrap (idempotent, needs NO GPU)
#
# Target: AutoDL container instance (Ubuntu 22.04, login as root) -- also runs on any
#         Linux box, where it degrades to "no apt, install under $HOME/toolchain".
#
# Usage:
#   bash bootstrap.sh                      # apt deps (if root) + fetch + extract + version assert
#   bash bootstrap.sh --check              # health check only, changes nothing
#   bash bootstrap.sh --tarball /path/blender-4.5.14-linux-x64.tar.xz   # use a pushed tarball
#   bash bootstrap.sh --prefix /opt        # default: /opt as root, $HOME/toolchain otherwise
#   bash bootstrap.sh --no-apt             # never call apt
#   bash bootstrap.sh --cjk                # also apt-install fonts-noto-cjk (root only)
#   bash bootstrap.sh --extra-libs         # no-root fallback: apt-get download the few system
#                                          # libs Blender needs (libsm6/libice6/...) and unpack
#                                          # them under $PREFIX/extralibs (used by the wrapper)
#   bash bootstrap.sh --force              # re-extract even if already present
#
# Env overrides: SHA256_EXPECT=<hash>  BASE_URL=<dir-url>  PREFIX=<dir>  CACHE_DIR=<dir>
#
# NOTE (paid for once): the launcher gets a WRAPPER SCRIPT, never a symlink -- Blender's
# tarball resolves its bundled libs through $ORIGIN/lib, and $ORIGIN follows the real binary
# path, so a symlink in /usr/local/bin makes all ~24 bundled libs "not found".
set -u

VER="4.5.14"
PKG="blender-${VER}-linux-x64"
TARBALL="${PKG}.tar.xz"
BASE_URL="${BASE_URL:-https://download.blender.org/release/Blender4.5}"
SHA256_EXPECT="${SHA256_EXPECT:-9ba871ff2ecd36526b77432745980b7e6664ecd0c7ca11c48849073dcfe06da3}"

IS_ROOT=0; [ "$(id -u)" = "0" ] && IS_ROOT=1
PREFIX=""; LOCAL_TAR=""; DO_APT=1; DO_CJK=0; DO_CHECK=0; DO_FORCE=0; DO_VERIFY=1; DO_EXTRALIBS=0

while [ $# -gt 0 ]; do
  case "$1" in
    --check)      DO_CHECK=1 ;;
    --no-apt)     DO_APT=0 ;;
    --cjk)        DO_CJK=1 ;;
    --force)      DO_FORCE=1 ;;
    --extra-libs) DO_EXTRALIBS=1 ;;
    --no-verify)  DO_VERIFY=0 ;;
    --prefix)     PREFIX="${2:-}"; shift ;;
    --tarball)    LOCAL_TAR="${2:-}"; shift ;;
    --blender-version) VER="${2:-}"; shift; PKG="blender-${VER}-linux-x64"; TARBALL="${PKG}.tar.xz" ;;
    -h|--help)    sed -n '2,25p' "$0"; exit 0 ;;
    *)            echo "unknown arg: $1" >&2; exit 2 ;;
  esac
  shift
done

[ -n "$PREFIX" ] || { if [ "$IS_ROOT" = 1 ]; then PREFIX=/opt; else PREFIX="$HOME/toolchain"; fi; }
DEST="$PREFIX/$PKG"
EXTRALIB="$PREFIX/extralibs"
BINDIR="/usr/local/bin"; [ "$IS_ROOT" = 1 ] || BINDIR="$HOME/bin"
CACHE="${CACHE_DIR:-$HOME/_dl}"
STAMP="$DEST/.bootstrap-ok"

APT_PKGS="ca-certificates curl xz-utils ffmpeg libx11-6 libxi6 libxxf86vm1 libxfixes3 \
libxrender1 libxkbcommon0 libsm6 libice6 libgl1 libegl1 libgomp1 libxext6 libxau6 libxdmcp6"
[ "$DO_CJK" = 1 ] && APT_PKGS="$APT_PKGS fonts-noto-cjk"
# libs that are NOT bundled inside the Blender tarball (no-root fallback candidate list)
EXTRALIB_PKGS="libsm6 libice6 libx11-6 libxi6 libxxf86vm1 libxfixes3 libxrender1 libxkbcommon0 libgomp1"

say() { printf '[bootstrap] %s\n' "$*"; }

# ---------------------------------------------------------------- wrapper + libs
write_wrapper() {  # $1 = real binary, $2 = extra lib dir (may be empty)
  local real="$1" extra="${2:-}"
  mkdir -p "$BINDIR"
  local tmp="$BINDIR/.blender.wrapper.$$"
  {
    echo '#!/bin/sh'
    echo '# generated by bootstrap.sh -- do not replace with a symlink (breaks $ORIGIN RPATH)'
    if [ -n "$extra" ]; then
      echo "BLENDER_LIBDIR=\"$extra\""
      echo 'if [ -n "$BLENDER_LIBDIR" ]; then'
      echo '  LD_LIBRARY_PATH="$BLENDER_LIBDIR${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"; export LD_LIBRARY_PATH'
      echo 'fi'
    else
      echo 'BLENDER_LIBDIR=""'
    fi
    echo "exec \"$real\" \"\$@\""
  } > "$tmp"
  chmod 0755 "$tmp"
  # NEVER write through $BINDIR/blender: if it is a leftover SYMLINK to the real binary,
  # `>` would follow it and clobber Blender's launcher (observed 2026-10-13: 181-byte
  # wrapper replaced the ELF -> the wrapper exec'd itself -> infinite exec loop).
  rm -f "$BINDIR/blender"
  mv -f "$tmp" "$BINDIR/blender"
}

missing_libs() {  # $1 = real binary, $2 = extra lib dir
  local real="$1" extra="${2:-}" out
  if [ -n "$extra" ]; then
    out="$(LD_LIBRARY_PATH="$extra" ldd "$real" 2>/dev/null | grep 'not found' || true)"
  else
    out="$(ldd "$real" 2>/dev/null | grep 'not found' || true)"
  fi
  printf '%s' "$out"
}

unpack_extralibs() {  # no-root fallback via `apt-get download` (works without root, needs network)
  local tmp; tmp="$(mktemp -d)"
  say "extra-libs: trying apt-get download ($EXTRALIB_PKGS)"
  ( cd "$tmp" && apt-get download $EXTRALIB_PKGS ) 2>&1 | tail -n 5 | sed 's/^/    /'
  mkdir -p "$EXTRALIB"
  local n=0
  for d in "$tmp"/*.deb; do
    [ -f "$d" ] || continue
    dpkg-deb -x "$d" "$EXTRALIB" 2>/dev/null && n=$((n+1))
  done
  rm -rf "$tmp"
  say "extra-libs: unpacked $n deb(s) into $EXTRALIB"
  [ "$n" -gt 0 ]
}

extra_ldpath() {  # where the unpacked debs actually put their .so files
  if [ -d "$EXTRALIB/usr/lib/x86_64-linux-gnu" ]; then
    printf '%s' "$EXTRALIB/usr/lib/x86_64-linux-gnu"
  else
    printf '%s' "$EXTRALIB"
  fi
}

# ---------------------------------------------------------------- check mode
if [ "$DO_CHECK" = 1 ]; then
  say "check mode: prefix=$PREFIX root=$IS_ROOT"
  if command -v blender >/dev/null 2>&1; then
    say "launcher: $(command -v blender)"
    V="$("$BINDIR/blender" --version 2>&1 | head -n 1)"
    say "version : $V"
    case "$V" in
      *"$VER"*) say "__CHECK__ ok=1 version=$VER"; exit 0 ;;
      *)        say "__CHECK__ ok=0 expected=$VER got=$V"; exit 1 ;;
    esac
  fi
  say "__CHECK__ ok=0 blender-not-on-PATH"; exit 1
fi

# ---------------------------------------------------------------- 1) system libraries
if [ "$DO_APT" = 1 ] && [ "$IS_ROOT" = 1 ]; then
  say "apt: installing runtime libs (the slow part of a 0.5-core no-GPU session)"
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq || say "apt-get update failed (continuing)"
  # shellcheck disable=SC2086
  apt-get install -y -qq --no-install-recommends $APT_PKGS || say "apt-get install reported errors (continuing)"
else
  say "apt: skipped (root=$IS_ROOT, --no-apt=$((1-DO_APT)))"
fi

# ---------------------------------------------------------------- 2) extract (unless already good)
# Integrity probe: Blender's real launcher is a multi-MB ELF. A tiny file means either the
# wrapper clobbered it (bug fixed 2026-10-13) or extraction was interrupted -> re-extract.
NEED_EXTRACT=1
if [ "$DO_FORCE" != 1 ] && [ -f "$STAMP" ] && [ -f "$DEST/blender" ]; then
  SZ="$(stat -c%s "$DEST/blender" 2>/dev/null || echo 0)"
  if [ "$SZ" -gt 1000000 ]; then
    say "already extracted (launcher ${SZ} B)"
    NEED_EXTRACT=0
  else
    say "launcher is only ${SZ} B -> clobbered or partial install, re-extracting"
  fi
fi

if [ "$NEED_EXTRACT" = 1 ]; then
  mkdir -p "$CACHE"
  TAR_PATH=""
  if [ -n "$LOCAL_TAR" ]; then
    [ -f "$LOCAL_TAR" ] || { say "FATAL: tarball not found: $LOCAL_TAR"; exit 3; }
    TAR_PATH="$LOCAL_TAR"; say "using local tarball: $TAR_PATH"
  elif [ -f "$CACHE/$TARBALL" ]; then
    TAR_PATH="$CACHE/$TARBALL"; say "using cached tarball: $TAR_PATH"
  else
    for url in "$BASE_URL/$TARBALL" "https://download.blender.org/release/Blender4.5/$TARBALL"; do
      say "downloading $url"
      if curl -fL --retry 3 --retry-delay 2 -C - --max-time 1800 -o "$CACHE/$TARBALL" "$url"; then
        TAR_PATH="$CACHE/$TARBALL"; break
      fi
      say "download failed: $url"
    done
  fi
  [ -n "$TAR_PATH" ] || { say "FATAL: no tarball available"; exit 4; }
  say "tarball: $TAR_PATH ($(stat -c%s "$TAR_PATH" 2>/dev/null || echo '?') bytes)"

  if [ "$DO_VERIFY" = 1 ] && [ -n "$SHA256_EXPECT" ]; then
    got="$(sha256sum "$TAR_PATH" | cut -d' ' -f1)"
    if [ "$got" = "$SHA256_EXPECT" ]; then
      say "sha256 OK: $got"
    else
      say "FATAL: sha256 mismatch"; say "  expect $SHA256_EXPECT"; say "  got    $got"; exit 5
    fi
  fi

  mkdir -p "$PREFIX"
  say "extracting to $PREFIX (xz, single-threaded; ~1-3 min)"
  rm -rf "$DEST"
  tar -xJf "$TAR_PATH" -C "$PREFIX" || { say "FATAL: extraction failed"; exit 6; }
  [ -f "$DEST/blender" ] || { say "FATAL: $DEST/blender missing after extraction"; exit 7; }
  SZ="$(stat -c%s "$DEST/blender" 2>/dev/null || echo 0)"
  [ "$SZ" -gt 1000000 ] || { say "FATAL: extracted launcher is only ${SZ} B (archive incomplete?)"; exit 7; }
  date -u +%Y-%m-%dT%H:%M:%SZ > "$STAMP"
fi

# ---------------------------------------------------------------- 3) wrapper (+ no-root libs)
write_wrapper "$DEST/blender" ""
MISS="$(missing_libs "$DEST/blender" "")"
if [ -n "$MISS" ]; then
  say "missing system libs:"
  printf '%s\n' "$MISS" | sed 's/^/    /'
  if [ "$DO_EXTRALIBS" = 1 ] || [ "$IS_ROOT" != 1 ]; then
    if unpack_extralibs; then write_wrapper "$DEST/blender" "$(extra_ldpath)"; fi
  fi
fi

V_LINE="$("$BINDIR/blender" --version 2>&1 | head -n 1)"
case "$V_LINE" in
  "Blender $VER"*) say "version OK: $V_LINE" ;;
  *)               say "WARN: unexpected version line: $V_LINE" ;;
esac
MISS2="$(missing_libs "$DEST/blender" "$([ -d "$EXTRALIB" ] && extra_ldpath)")"
[ -z "$MISS2" ] || say "WARN: still missing: $(printf '%s' "$MISS2" | tr '\n' ' ')"

say "launcher: $BINDIR/blender -> $DEST/blender (wrapper; LD_LIBRARY_PATH=$( [ -d "$EXTRALIB" ] && extra_ldpath ))"
say "__BOOTSTRAP__ ok=1 skipped=$((1-NEED_EXTRACT)) path=$DEST prefix=$PREFIX missing_libs=$(printf '%s' "$MISS2" | grep -c . || true)"
